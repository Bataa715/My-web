/**
 * One memory-aid word per basic kana. Hiragana uses everyday native words;
 * katakana uses common loanwords (what katakana is mostly used for).
 */
export interface KanaExample {
  word: string;
  /** romaji reading */
  reading: string;
  /** Mongolian meaning */
  mn: string;
}

type Row = [char: string, word: string, reading: string, mn: string];

const build = (rows: Row[]): Record<string, KanaExample> =>
  Object.fromEntries(rows.map(([c, word, reading, mn]) => [c, { word, reading, mn }]));

